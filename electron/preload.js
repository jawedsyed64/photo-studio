// Exposes a small, safe API to the editor page.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('photoStudio', {
  openImages: multi => ipcRenderer.invoke('open-images', multi),
  readFile: p => ipcRenderer.invoke('read-file', p),
  readText: p => ipcRenderer.invoke('read-text', p),
  exists: p => ipcRenderer.invoke('exists', p),
  saveDialog: (name, filters) => ipcRenderer.invoke('save-dialog', name, filters),
  chooseFolder: () => ipcRenderer.invoke('choose-folder'),
  writeFile: (p, bytes) => ipcRenderer.invoke('write-file', p, bytes),
  writeText: (p, text) => ipcRenderer.invoke('write-text', p, text),
  openProject: () => ipcRenderer.invoke('open-project'),
  storeGet: key => ipcRenderer.invoke('store-get', key),
  storeSet: (key, value) => ipcRenderer.invoke('store-set', key, value),
  setSecret: (name, value) => ipcRenderer.invoke('set-secret', name, value),
  hasSecret: name => ipcRenderer.invoke('has-secret', name),
  showInFolder: p => ipcRenderer.invoke('show-in-folder', p),
  joinPath: (...parts) => ipcRenderer.invoke('join-path', ...parts),
  userDataPath: () => ipcRenderer.invoke('user-data'),
  version: () => ipcRenderer.invoke('version'),
  onOpenFile: cb => ipcRenderer.on('open-file', (_e, p) => cb(p)),
  assetSave: (docId, id, bytes) => ipcRenderer.invoke('asset-save', docId, id, bytes),
  assetLoad: (docId, id) => ipcRenderer.invoke('asset-load', docId, id),
  ai: {
    models: () => ipcRenderer.invoke('ai-models'),
    download: id => ipcRenderer.invoke('ai-download', id),
    cancelDownload: id => ipcRenderer.invoke('ai-cancel-download', id),
    deleteModel: id => ipcRenderer.invoke('ai-delete-model', id),
    run: payload => ipcRenderer.invoke('ai-run', payload),
    cancel: job => ipcRenderer.invoke('ai-cancel', job),
    online: (kind, args) => ipcRenderer.invoke('ai-online', kind, args),
    hasKey: () => ipcRenderer.invoke('ai-has-key'),
    onDownloadProgress: cb => { const f = (_e, d) => cb(d); ipcRenderer.on('ai-download-progress', f); return () => ipcRenderer.removeListener('ai-download-progress', f); },
    onProgress: cb => { const f = (_e, d) => cb(d); ipcRenderer.on('ai-progress', f); return () => ipcRenderer.removeListener('ai-progress', f); },
    onOnlineStatus: cb => { const f = (_e, d) => cb(d); ipcRenderer.on('ai-online-status', f); return () => ipcRenderer.removeListener('ai-online-status', f); },
  },
  pathForFile: file => { try { return webUtils.getPathForFile(file); } catch { return null; } },
});
